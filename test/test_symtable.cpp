TEST_F(SymTableTest, InsertDuplicateId) {
    paramData params1[] = {{"x", INT}};
    paramData params2[] = {{"y", DOUBLE}};

    // First insertion should succeed
    int firstInsert = symTableInsertFun("sharedName", INT, 1, params1);
    EXPECT_EQ(firstInsert, 0);
    EXPECT_EQ(symTableGetFunNum(), 1);

    // Second insertion with the same ID should return 1 (already in use)
    int secondInsert = symTableInsertFun("sharedName", DOUBLE, 1, params2);
    EXPECT_EQ(secondInsert, 1);

    // Ensure table count remains unchanged and original data is preserved
    EXPECT_EQ(symTableGetFunNum(), 1);
    funData fd = symTableFindFun("sharedName");
    EXPECT_EQ(fd.retType, INT); // Should still be the original type
}

