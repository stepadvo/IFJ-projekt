TEST_F(SymTableTest, InsertManyFunctions33Plus) {
    const int totalFunctions = 40; // Safely above the 33 boundary

    for (int i = 0; i < totalFunctions; ++i) {
        char funcName[32];
        std::snprintf(funcName, sizeof(funcName), "func_%d", i);

        int result = symTableInsertFun(funcName, INT, 0, nullptr);
        EXPECT_EQ(result, 0) << "Failed at insertion index: " << i;
    }

    // Verify total count matches
    EXPECT_EQ(symTableGetFunNum(), totalFunctions);
    EXPECT_FALSE(symTableIsEmpty());

    // Verify lookup works correctly for boundaries (e.g., 32 and 39)
    funData fd32 = symTableFindFun("func_32");
    ASSERT_NE(fd32.id, nullptr);
    EXPECT_STREQ(fd32.id, "func_32");

    funData fd39 = symTableFindFun("func_39");
    ASSERT_NE(fd39.id, nullptr);
    EXPECT_STREQ(fd39.id, "func_39");
}
