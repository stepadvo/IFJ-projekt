// 7. Finding a Variable in the Current Block
TEST_F(SymTableTest, FindVarCurrBlock_Scenarios) {
    paramData params[] = {{"paramName", BOOL}};
    ASSERT_EQ(symTableInsertFun("func", INT, 1, params), 0);
    ASSERT_EQ(symTableActivateFun("func"), 0);

    // 3. When blockDepth = 0 (only parameters searched by currBlock or table)
    // blockDepth is 0 (no blocks opened yet)
    varData vParamZero = symTableFindVarCurrBlock("paramName");
    // When blockDepth < 1, only parameters are searched
    ASSERT_NE(vParamZero.id, nullptr);
    EXPECT_STREQ(vParamZero.id, "paramName");
    EXPECT_EQ(vParamZero.dataType, BOOL);

    // Open block 1 (blockDepth = 1)
    ASSERT_EQ(beginBlock(), 1);
    ASSERT_EQ(symTableInsertVar("block1Var", INT, false), 0);

    // 4. When blockDepth = 1 (both parameters and variables in block 1
    // searched)
    varData vParamOne = symTableFindVarCurrBlock("paramName");
    ASSERT_NE(vParamOne.id, nullptr);
    EXPECT_STREQ(vParamOne.id, "paramName");

    varData vBlock1 = symTableFindVarCurrBlock("block1Var");
    ASSERT_NE(vBlock1.id, nullptr);
    EXPECT_STREQ(vBlock1.id, "block1Var");

    // Open block 2 (blockDepth = 2)
    ASSERT_EQ(beginBlock(), 2);
    ASSERT_EQ(symTableInsertVar("block2Var", DOUBLE, false), 0);

    // 1. Supposed to be found in current block
    varData vBlock2Found = symTableFindVarCurrBlock("block2Var");
    ASSERT_NE(vBlock2Found.id, nullptr);
    EXPECT_STREQ(vBlock2Found.id, "block2Var");

    // 2. Not supposed to be found in current block (variable exists in block 1,
    // but we are in block 2)
    varData vBlock1FromBlock2 = symTableFindVarCurrBlock("block1Var");
    EXPECT_EQ(vBlock1FromBlock2.id, nullptr); // Not in current block (block 2)
}
