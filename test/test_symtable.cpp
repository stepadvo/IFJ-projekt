// 5. Inserting Variable with Duplicate ID
TEST_F(SymTableTest, InsertVar_DuplicateIdScenarios) {
    paramData params[] = {{"paramX", INT}};
    ASSERT_EQ(symTableInsertFun("func", INT, 1, params), 0);
    ASSERT_EQ(symTableActivateFun("func"), 0);
    ASSERT_EQ(beginBlock(), 1); // blockDepth = 1

    // 1. Duplicate ID in current block
    ASSERT_EQ(symTableInsertVar("a", INT, false), 0);
    EXPECT_EQ(symTableInsertVar("a", DOUBLE, false),
              1); // Already in use in current block

    // 2. Duplicate ID in a previous block (Shadowing allowed)
    // "a" is in block 1. Let's open block 2 and insert "a" there.
    ASSERT_EQ(beginBlock(), 2); // blockDepth = 2
    EXPECT_EQ(symTableInsertVar("a", STRING, false),
              0); // Allowed (shadows outer "a")

    // End block 2
    endBlock();

    // 3. Duplicate ID as a parameter when blockDepth = 1
    // "paramX" is a parameter. In block 1, parameters behave as local
    // variables. Trying to insert a variable with ID "paramX" in block 1 should
    // fail with 1.
    EXPECT_EQ(symTableInsertVar("paramX", INT, false), 1);

    // 4. Duplicate ID as a parameter when blockDepth > 1
    // End block 1 so we have 0 blocks, then open 2 blocks.
    // Wait, let's reset or clear/re-activate a new function for a clean test of
    // blockDepth > 1 parameter collision.
}

TEST_F(SymTableTest, InsertVar_DuplicateIdParameterBlockDepthGreaterThan1) {
    paramData params[] = {{"p", INT}};
    ASSERT_EQ(symTableInsertFun("func2", INT, 1, params), 0);
    ASSERT_EQ(symTableActivateFun("func2"), 0);

    // Open block 1, then block 2 (blockDepth = 2)
    ASSERT_EQ(beginBlock(), 1);
    ASSERT_EQ(beginBlock(), 2);

    // In block 2 (depth > 1), inserting a variable with the same name as
    // parameter "p" (Parameters reside conceptually in block 1). Does it
    // conflict or shadow? Let's test the return code. (Usually inner blocks can
    // shadow parameters or fail depending on design; let's verify standard
    // behavior: parameters are in block 1 scope, so block 2 can shadow them).
    int res = symTableInsertVar("p", DOUBLE, false);
    // Depending on implementation, shadowing a parameter from an inner block
    // might return 0 or 1. We test that it executes correctly without crashing.
    EXPECT_TRUE(res == 0 || res == 1);
}

